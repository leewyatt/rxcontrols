package io.github.leewyatt.rxcontrols;

/**
 * Defines how an optional carousel overlay element is displayed.
 */
public enum DisplayMode {

    /**
     * Always show the element.
     */
    SHOW,

    /**
     * Always hide the element.
     */
    HIDE,

    /**
     * Show the element while the carousel is hovered, and hide it otherwise.
     */
    AUTO;
}
