package io.github.leewyatt.rxcontrols;

/**
 * Axes that a smooth scroll handler may drive.
 */
public enum ScrollAxis {
    /**
     * Vertical scrolling only.
     */
    VERTICAL,

    /**
     * Horizontal scrolling only.
     */
    HORIZONTAL,

    /**
     * Horizontal and vertical scrolling.
     */
    BOTH
}
