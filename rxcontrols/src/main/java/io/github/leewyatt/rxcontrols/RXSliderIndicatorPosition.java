package io.github.leewyatt.rxcontrols;

/**
 * Side of the track on which a slider's value indicator bubble is placed.
 */
public enum RXSliderIndicatorPosition {

    /**
     * Horizontal orientation: above the track. Vertical orientation: to the
     * left of the track.
     */
    ABOVE,

    /**
     * Horizontal orientation: below the track. Vertical orientation: to the
     * right of the track.
     */
    BELOW
}
