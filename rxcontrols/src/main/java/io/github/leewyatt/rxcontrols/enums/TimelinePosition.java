package io.github.leewyatt.rxcontrols.enums;

/**
 * Which side of a vertical timeline the axis column (dot and connector) sits on.
 */
public enum TimelinePosition {
    /**
     * Axis on the left, content on the right (the default).
     */
    LEFT,
    /**
     * Axis on the right, content on the left and right-aligned toward the axis.
     */
    RIGHT
}
